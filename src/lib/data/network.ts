function statusFor(capacityPct: number, kind: Facility["kind"]): FacilityStatus {
  if (capacityPct >= 95) return "over-capacity";
  if (capacityPct >= 88) return "near-capacity";
  if (kind === "cross-dock" && capacityPct < 55) return "reduced";
  return "operational";
}

export const FACILITIES: Facility[] = SEEDS.map((seed, i) => {
  const palletPositions = Math.round(seed.floorArea * 1.35);
  const dwellBase = seed.kind === "cross-dock" ? 48 : seed.kind === "port" ? 186 : 124;
  return {
    id: `FAC-${seed.code}`,
    code: seed.code,
    name: seed.name,
    city: seed.city,
    country: seed.country,
    countryCode: seed.countryCode,
    region: seed.region,
    geo: seed.geo,
    kind: seed.kind,
    capacityPct: seed.capacityPct,
    inbound: seed.inbound,
    outbound: seed.outbound,
    staffOnShift: Math.round(seed.dockDoors * 2.4 + (i % 5) * 3),
    staffPlanned: Math.round(seed.dockDoors * 2.6 + (i % 5) * 3),
    throughputToday: seed.inbound + seed.outbound,
    throughputTarget: Math.round((seed.inbound + seed.outbound) * 1.12),
    dockDoors: seed.dockDoors,
    docksInUse: Math.round(seed.dockDoors * (seed.capacityPct / 100) * 0.92),
    floorArea: seed.floorArea,
    palletPositions,
    palletsStored: Math.round(palletPositions * (seed.capacityPct / 100)),
    status: statusFor(seed.capacityPct, seed.kind),
    shiftPattern: seed.shiftPattern,
    manager: seed.manager,
    dwellMinutes: dwellBase + ((i * 17) % 40) - 20,
  };
});

export const FACILITY_BY_ID = new Map(FACILITIES.map((f) => [f.id, f]));

export function facility(id: string): Facility {
  const f = FACILITY_BY_ID.get(id);
  if (!f) throw new Error(`Unknown facility ${id}`);
  return f;
}

